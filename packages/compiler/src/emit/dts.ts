import type { Catalog } from '../author/lint';

/**
 * `messages.d.ts`: one entry per key with the types of its slot values, merged into
 * `pixi-silk/i18n`'s `SilkMessageRegistry`, so `prepare({ coins: { key: 'shop.coins', values: { count } } })`
 * is checked at compile time. Keys are sorted, so the output only changes when messages do.
 */
export function emitMessagesDts(catalog: Catalog): string {
    const lines = ['// Generated by silk compile. Do not edit.', '', 'export interface SilkMessages {'];

    for (const key of [...catalog.messages.keys()].sort()) {
        const message = catalog.messages.get(key);

        if (!message) continue;
        const slots = [...message.slots].sort((a, b) => (a.name < b.name ? -1 : 1));
        const body = slots.length
            ? `{ ${slots.map((s) => `${s.name}: ${s.type === 'number' ? 'number' : 'string'};`).join(' ')} }`
            : 'Record<string, never>';
        const doc = message.context
            ? `    /** ${message.context.replace(/\*\//g, '* /').replace(/\s+/g, ' ')} */\n`
            : '';

        lines.push(`${doc}    ${JSON.stringify(key)}: ${body};`);
    }
    lines.push(
        '}',
        '',
        "declare module 'pixi-silk/i18n' {",
        '    interface SilkMessageRegistry extends SilkMessages {}',
        '}',
        '',
    );

    return lines.join('\n');
}
