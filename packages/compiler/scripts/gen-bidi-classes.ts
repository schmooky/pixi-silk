/**
 * Generates src/shape/bidi-classes.ts from DerivedBidiClass.txt (Unicode 16.0.0): every code point
 * range with its exact bidi class, for the compiler's bidi pass. Compiler only: the runtime never
 * sees this table. Run scripts/fetch-ucd.ts first.
 *
 *   node scripts/gen-bidi-classes.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

const text = readFileSync(new URL('../.cache/ucd/DerivedBidiClass.txt', import.meta.url), 'utf8');
const ranges: [number, number, string][] = [];

for (const line of text.split('\n')) {
    const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/.exec(line);

    if (m) ranges.push([Number.parseInt(m[1], 16), Number.parseInt(m[2] ?? m[1], 16), m[3]]);
}
ranges.sort((a, b) => a[0] - b[0]);
// merge neighbours of the same class
const merged: [number, number, string][] = [];

for (const r of ranges) {
    const last = merged[merged.length - 1];

    if (last && last[2] === r[2] && last[1] + 1 === r[0]) last[1] = r[1];
    else merged.push([...r]);
}
const classes = [...new Set(merged.map((r) => r[2]))].sort();
const starts = merged.map((r) => r[0].toString(36)).join(',');
const ends = merged.map((r) => r[1].toString(36)).join(',');
const kinds = merged.map((r) => classes.indexOf(r[2]).toString(36)).join('');
const out = `// Generated by scripts/gen-bidi-classes.ts from Unicode 16.0.0 DerivedBidiClass.txt. Do not edit.
import type { BidiClass } from 'pixi-silk/text/bidi';

/** Unicode version of the table. */
export const BIDI_UNICODE_VERSION = '16.0.0';
const CLASSES = ${JSON.stringify(classes)} as const;
const STARTS = '${starts}'.split(',').map((s) => Number.parseInt(s, 36));
const ENDS = '${ends}'.split(',').map((s) => Number.parseInt(s, 36));
const KINDS = '${kinds}';

/** Exact bidi class of a code point (unlisted code points are L). */
export function exactBidiClass(cp: number): BidiClass {
    let lo = 0;
    let hi = STARTS.length - 1;

    while (lo <= hi) {
        const mid = (lo + hi) >> 1;

        if (cp < STARTS[mid]) hi = mid - 1;
        else if (cp > ENDS[mid]) lo = mid + 1;
        else return CLASSES[Number.parseInt(KINDS[mid], 36)] as BidiClass;
    }

    return 'L';
}
`;

writeFileSync(new URL('../src/shape/bidi-classes.ts', import.meta.url), out);
console.log(`${merged.length} ranges, ${classes.length} classes: ${classes.join(' ')}`);
