/**
 * Generates src/shape/linebreak-data.ts from Unicode 16.0.0 DerivedLineBreak.txt and
 * EastAsianWidth.txt (with their @missing defaults): the line break class of every code point and the
 * East Asian (F, W, H) ranges, for the compiler's UAX #14. Compiler only. Run scripts/fetch-ucd.ts first.
 *
 *   node scripts/gen-linebreak-data.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

const ucd = new URL('../.cache/ucd/', import.meta.url);

/** The @missing lines name values in full: the short names the data lines use. */
const LONG_NAMES: Record<string, string> = {
    Unknown: 'XX',
    Ideographic: 'ID',
    Prefix_Numeric: 'PR',
    Neutral: 'N',
    Wide: 'W',
    Fullwidth: 'F',
    Halfwidth: 'H',
    Narrow: 'Na',
    Ambiguous: 'A',
};

/** Code point to value, @missing defaults first, then the listed ranges. */
function load(file: string, fallback: string): (cp: number) => string {
    const values = new Array<string>(0x110000).fill(fallback);

    for (const line of readFileSync(new URL(file, ucd), 'utf8').split('\n')) {
        const missing = /^#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+)\s*;\s*(\w+)/.exec(line);
        const m = missing ?? /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/.exec(line);

        if (!m) continue;
        const end = Number.parseInt(m[2] ?? m[1], 16);

        const value = LONG_NAMES[m[3]] ?? m[3];

        for (let cp = Number.parseInt(m[1], 16); cp <= end; cp++) values[cp] = value;
    }
    return (cp) => values[cp];
}

function ranges(get: (cp: number) => string): [number, number, string][] {
    const out: [number, number, string][] = [];

    for (let cp = 0; cp < 0x110000; cp++) {
        const v = get(cp);
        const last = out[out.length - 1];

        if (last && last[2] === v && last[1] === cp - 1) last[1] = cp;
        else out.push([cp, cp, v]);
    }
    return out;
}

const lb = ranges(load('LineBreak.txt', 'XX'));
const ea = ranges(load('EastAsianWidth.txt', 'N')).filter((r) => r[2] === 'F' || r[2] === 'W' || r[2] === 'H');
const classes = [...new Set(lb.map((r) => r[2]))].sort();
const b36 = (n: number) => n.toString(36);
const out = `// Generated by scripts/gen-linebreak-data.ts from Unicode 16.0.0. Do not edit.

/** Unicode version of the tables. */
export const LINEBREAK_UNICODE_VERSION = '16.0.0';
/** Line break classes, by index. */
export const LB_CLASSES = ${JSON.stringify(classes)} as const;
/** Start of each range, base 36. */
export const LB_STARTS = '${lb.map((r) => b36(r[0])).join(',')}';
/** Class index of each range, base 36, two characters each. */
export const LB_KINDS = '${lb.map((r) => b36(classes.indexOf(r[2])).padStart(2, '0')).join('')}';
/** East Asian Width F, W or H: start and end of each range, base 36. */
export const EA_RANGES = '${ea.map((r) => `${b36(r[0])}-${b36(r[1])}`).join(',')}';
`;

writeFileSync(new URL('../src/shape/linebreak-data.ts', import.meta.url), out);
console.log(
    `${lb.length} line break ranges, ${classes.length} classes, ${ea.length} East Asian ranges, ${(out.length / 1024).toFixed(0)} kB`,
);
